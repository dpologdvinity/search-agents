"""Benchmark: how far line solving gets alone, and what the hybrid search and the SAT solver cost.

    python -m nonogram benchmark            # print the table
    python -m nonogram benchmark --write    # also write results/nonogram_benchmark.{json,md}

The set is the twelve library pictures plus seeded random pictures of 10x10, 15x15 and 20x20 (ten each).
Every puzzle is solved by all three methods with no search budget, except SAT, which stops after
SAT_PROPAGATIONS_BENCH implied literals; a stop is reported as "undecided". Times are wall-clock on the
machine that ran the benchmark, so they are a relative guide. The counts (guesses, conflicts, propagations,
backtracks) do not depend on the machine: they are the same on every run with the same seeds.
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

from .generate import random_puzzle
from .library import library
from .puzzle import Puzzle
from .solvers import SAT_PROPAGATIONS_BENCH, solve

RESULTS = Path(__file__).resolve().parent.parent / "results"
RANDOM_SIZES = (10, 15, 20)
RANDOM_SEEDS = 10
METHODS = ("line", "hybrid", "sat")


def puzzle_set(random_sizes=RANDOM_SIZES, seeds: int = RANDOM_SEEDS) -> list[tuple[str, Puzzle]]:
    """(group, puzzle) pairs: the library first, then the random puzzles of each size."""
    items = [("library", p) for p in library()]
    for size in random_sizes:
        for seed in range(1, seeds + 1):
            puzzle, _, _ = random_puzzle(size, size, seed=seed)
            items.append((f"random {size}x{size}", puzzle))
    return items


def run(random_sizes=RANDOM_SIZES, seeds: int = RANDOM_SEEDS) -> dict:
    """Solve every puzzle with every method and collect the per-puzzle rows and per-group summaries."""
    rows = []
    for group, puzzle in puzzle_set(random_sizes, seeds):
        row = {"puzzle": puzzle.id or puzzle.name.lower().replace(" ", "-"), "group": group,
               "rows": puzzle.rows, "cols": puzzle.cols}
        for method in METHODS:
            budget = SAT_PROPAGATIONS_BENCH if method == "sat" else None
            res = solve(puzzle, method, max_propagations=budget)
            s = res.stats
            row[method] = {
                "status": res.status,
                "seconds": round(s.seconds, 4),
                "decisions": s.decisions,
                "conflicts": s.conflicts,
                "propagations": s.propagations,
                "backtracks": s.backtracks,
                "variables": s.variables,
                "clauses": s.clauses,
            }
        rows.append(row)
    return {"rows": rows, "summary": summarise(rows), "config": {
        "random_sizes": list(random_sizes), "random_seeds": seeds, "sat_propagation_budget": SAT_PROPAGATIONS_BENCH,
    }}


def summarise(rows: list[dict]) -> dict:
    """Per group: how many puzzles each method finished, and median and worst times and counts."""
    groups: dict[str, list[dict]] = {}
    for row in rows:
        groups.setdefault(row["group"], []).append(row)
    groups["all"] = rows
    out = {}
    for name, items in groups.items():
        entry = {"puzzles": len(items), "line_alone_finishes": sum(r["line"]["status"] == "unique" for r in items)}
        for method in METHODS:
            ok = [r[method] for r in items if r[method]["status"] in ("unique", "multiple", "contradiction")]
            entry[method] = {
                "finished": len(ok),
                "undecided": len(items) - len(ok),
                "median_seconds": round(statistics.median(m["seconds"] for m in ok), 4) if ok else None,
                "max_seconds": round(max((m["seconds"] for m in ok), default=0.0), 4),
                "median_decisions": statistics.median(m["decisions"] for m in ok) if ok else None,
                "max_propagations": max((m["propagations"] for m in ok), default=0),
            }
        out[name] = entry
    return out


def to_markdown(result: dict) -> str:
    """The results file: the summary table, then one row per puzzle."""
    lines = ["# Nonogram benchmark", "",
             "Line solving alone, the hybrid search (line passes plus guesses), and the SAT solver (DPLL on the "
             "automaton encoding). Generated by `python -m nonogram benchmark --write`. Times are wall-clock on the "
             "machine that ran it; counts are deterministic for the seeds used.", "",
             "## Summary", "",
             "| group | puzzles | line alone finishes | hybrid median s | hybrid max s "
             "| SAT median s | SAT max s | SAT undecided |",
             "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for name, e in result["summary"].items():
        lines.append(
            f"| {name} | {e['puzzles']} | {e['line_alone_finishes']} | {e['hybrid']['median_seconds']} | "
            f"{e['hybrid']['max_seconds']} | {e['sat']['median_seconds']} | {e['sat']['max_seconds']} | "
            f"{e['sat']['undecided']} |")
    lines += ["", "## Per puzzle", "",
              "| puzzle | size | line | line s | hybrid | guesses | conflicts | props | backtracks | SAT | SAT s | "
              "vars | clauses | decisions | conflicts | props | backtracks |",
              "|---|---|---|---:|---|---:|---:|---:|---:|---|---:|---:|---:|---:|---:|---:|---:|"]
    for r in result["rows"]:
        h, s, ln = r["hybrid"], r["sat"], r["line"]
        lines.append(
            f"| {r['puzzle']} | {r['rows']}x{r['cols']} | {ln['status']} | {ln['seconds']} | {h['status']} | "
            f"{h['decisions']} | {h['conflicts']} | {h['propagations']} | {h['backtracks']} | {s['status']} | "
            f"{s['seconds']} | {s['variables']} | {s['clauses']} | {s['decisions']} | {s['conflicts']} | "
            f"{s['propagations']} | {s['backtracks']} |")
    return "\n".join(lines) + "\n"


def write_results(result: dict) -> tuple[Path, Path]:
    """Write results/nonogram_benchmark.json and .md; returns the two paths."""
    RESULTS.mkdir(exist_ok=True)
    json_path = RESULTS / "nonogram_benchmark.json"
    md_path = RESULTS / "nonogram_benchmark.md"
    json_path.write_text(json.dumps(result, indent=1) + "\n")
    md_path.write_text(to_markdown(result))
    return json_path, md_path
