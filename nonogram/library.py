@lru_cache(maxsize=1)
def library() -> tuple[Puzzle, ...]:
    """Every picture as a Puzzle, in list order. Built once; the clues are computed from the art."""
    return tuple(Puzzle.from_picture(name, art, id=pid) for pid, name, art in PICTURES)


def get(pid: str) -> Puzzle | None:
    """The library puzzle with this id, or None."""
    for puzzle in library():
        if puzzle.id == pid:
            return puzzle
    return None
